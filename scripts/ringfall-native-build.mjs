/**
 * Builds the RINGFALL Dial-fill WASM when a Rust toolchain is present, and embeds it as
 * `src/ringfall/sim/native/fill-wasm.ts` (base64) so Node and the Vite build need no rustc.
 * Without rustc/cargo the committed embed is kept; nav.ts falls back to the TypeScript fill
 * when the module fails to instantiate or `RINGFALL_FILL=ts`.
 *
 *   node scripts/ringfall-native-build.mjs
 */
import { spawnSync } from "node:child_process";
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const crate = join(root, "native/ringfall-fill");
const outDir = join(root, "src/ringfall/sim/native");
const outWasm = join(outDir, "ringfall_fill.wasm");
const outEmbed = join(outDir, "fill-wasm.ts");

function writeEmbed(wasmPath) {
  const b64 = readFileSync(wasmPath).toString("base64");
  writeFileSync(
    outEmbed,
    `/** Auto-generated by scripts/ringfall-native-build.mjs — do not edit. */\nexport const RINGFALL_FILL_WASM_BASE64 = "${b64}";\n`,
  );
  console.log(`ringfall-native-build: wrote ${outEmbed} (${b64.length} b64 chars)`);
}

const rustc = spawnSync("rustc", ["--version"], { encoding: "utf8" });
const cargo = spawnSync("cargo", ["--version"], { encoding: "utf8" });
if (rustc.status !== 0 || cargo.status !== 0) {
  if (existsSync(outEmbed) || existsSync(outWasm)) {
    if (existsSync(outWasm) && !existsSync(outEmbed)) writeEmbed(outWasm);
    console.log("ringfall-native-build: no Rust toolchain; keeping committed WASM embed");
    process.exit(0);
  }
  console.warn("ringfall-native-build: no Rust toolchain and no committed WASM; TS fill fallback");
  process.exit(0);
}

spawnSync("rustup", ["target", "add", "wasm32-unknown-unknown"], { encoding: "utf8", cwd: root });

const build = spawnSync(
  "cargo",
  ["build", "--release", "--target", "wasm32-unknown-unknown", "--manifest-path", join(crate, "Cargo.toml")],
  { encoding: "utf8", cwd: root },
);
if (build.status !== 0) {
  console.error(build.stderr || build.stdout || "cargo build failed");
  process.exit(build.status ?? 1);
}

const built = join(crate, "target/wasm32-unknown-unknown/release/ringfall_fill.wasm");
if (!existsSync(built)) {
  console.error(`ringfall-native-build: missing ${built}`);
  process.exit(1);
}
mkdirSync(outDir, { recursive: true });
copyFileSync(built, outWasm);
writeEmbed(outWasm);
console.log(`ringfall-native-build: wrote ${outWasm}`);
